font=ImageFont.truetype('C:/Windows/Fonts/arial.ttf',23)
def frame(i,t):
    p=subprocess.run([str(FF),'-v','error','-ss',str(t),'-i',str(BASE/'final'/f'episode-{i}.mp4'),'-frames:v','1','-f','image2pipe','-vcodec','png','-'],capture_output=True,check=True)
    return Image.open(io.BytesIO(p.stdout)).convert('RGB')
def build(item):
    i,times=item
    dst=ROOT/f'episode-{i}-event.jpg'
    if dst.exists(): return i
    ims=[('REFERENCE',Image.open(BASE.parent/f'episode-{i}-keyframe.png').convert('RGB'))]+[(f'{t:.3f}s',frame(i,t)) for t in times]
    sheet=Image.new('RGB',(2560,1552),'#142344')
    d=ImageDraw.Draw(sheet)
    for n,(label,im) in enumerate(ims):
        x=(n%4)*640;y=(n//4)*388
        d.text((x+8,y+1),f'{i} | {label}',font=font,fill='white')
        im.thumbnail((640,360))
        sheet.paste(im,(x+(640-im.width)//2,y+28+(360-im.height)//2))
    sheet.save(dst,quality=92)
    return i
