import assert from 'node:assert/strict'
import { parseEther } from 'ethers'
import { commercialProposal, commercialScenario } from './plan-commercial-round.mjs'
const p=commercialProposal()
assert.equal(p.unitPriceWei,null);assert.equal(p.startsAt,null);assert.equal(p.endsAt,'0')
assert.equal(p.userConfirmed.saleEndPreference,'SELL_OUT_WITHOUT_CALENDAR_DEADLINE')
assert.equal(p.recommendation.finiteRoundDays,null)
assert.equal(p.recommendation.endPolicyImplemented,true)
assert.equal(p.recommendation.endPolicyPubliclyDeployed,false)
assert.equal(p.recommendation.proceedsSplitApproved,true)
assert.equal(p.userConfirmed.saleCapTokens,'4200000')
assert.equal(p.userConfirmed.walletCapTokens,'4200000')
assert.equal(p.recommendation.walletCapTokens,p.userConfirmed.saleCapTokens)
assert.equal(p.userConfirmed.lpPrincipalLock,'ONE_YEAR_AFTER_INITIAL_LP_CREATION')
assert.equal(p.recommendation.lpLockDurationApproved,true)
assert.equal(p.recommendation.lpLockImplementationVerified,false)
for(const s of [...p.scenarios,...p.splitComparison]){
  const gross=BigInt(s.grossReferenceUsd)
  const bps=BigInt(s.lpShareOfGrossEthBps)
  assert.equal(BigInt(s.buyerTokens),gross*14n)
  assert.equal(BigInt(s.separateMatchingLpTokens),gross*14n*bps/10000n)
  assert.equal(s.nominalInitialLpBothSidesReferenceUsd,s.lpEthReferenceUsd*2)
  assert.equal(s.grossReferenceUsd,s.lpEthReferenceUsd+s.operationsReferenceUsdBeforeCosts)
  assert.equal(parseEther(s.maximumPaymentEth),parseEther(s.lpEth)+parseEther(s.operationsEthBeforeCosts))
  assert.ok(parseEther(s.lpEth)*10000n<=parseEther(s.maximumPaymentEth)*bps)
  assert.ok(parseEther(s.maximumPaymentEth)*bps-parseEther(s.lpEth)*10000n<10000n)
}
assert.equal(commercialScenario(300000,'3000').buyerTokens,'4200000')
assert.equal(commercialScenario(300000,'3000').nominalInitialLpBothSidesReferenceUsd,300000)
assert.equal(commercialScenario(300000,'3000').separateMatchingLpTokens,'2100000')
assert.equal(commercialScenario(300000,'3000').operationsReferenceUsdBeforeCosts,150000)
assert.equal(commercialScenario(300000,'3000',1500).nominalInitialLpBothSidesReferenceUsd,90000)
assert.equal(commercialScenario(300000,'3000',1500).separateMatchingLpTokens,'630000')
for(const bps of [0,-1,1.5,10001,NaN])assert.throws(()=>commercialScenario(300000,'3000',bps))
assert.throws(()=>commercialScenario(300001,'3000'));assert.throws(()=>commercialScenario(-1,'3000'))
console.log('PASS: 15/85 and 50/50 proposals, separate LP stock, exact wei conservation, no-deadline preference and unconfigured deployment gates.')
